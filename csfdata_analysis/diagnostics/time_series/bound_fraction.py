"""Instantaneous stellar bound membership and fractions."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from amuse.datamodel import Particles
from amuse.units import constants, units
from amuse.units.quantities import Quantity

from csfdata_analysis.diagnostics.base import (
    EvaluationChoice,
    ParticleField,
    ParticleSnapshotResult,
    SnapshotDiagnosticResult,
    TimeSeriesDiagnostic,
)


DEFAULT_MAX_ITERATIONS = 10
"""Maximum membership updates used by the version-1 diagnostic."""

DEFAULT_MAX_MATRIX_BYTES = 256 * 1024**2
"""Per-snapshot memory budget for exact distance calculations."""

GRAVITATIONAL_CONSTANT = constants.G.value_in(
    units.pc * units.kms**2 / units.MSun
)
"""Gravitational constant in the diagnostic's canonical units."""


@dataclass(frozen=True)
class BoundFractionResult:
    """One snapshot's standalone stellar bound-fraction calculation.

    Particle labels follow the input order: ``1`` is self-bound, ``0`` is
    self-unbound, and ``-1`` marks a particle excluded by input validation.
    Fractions use valid particles and valid stellar mass as their denominators.
    """

    particle_key: np.ndarray
    bound: np.ndarray
    centre_position: Quantity
    centre_velocity: Quantity
    n_present: int
    n_valid: int
    n_bound: int
    stellar_mass: Quantity
    bound_mass: Quantity
    bound_number_fraction: float
    bound_mass_fraction: float
    n_iterations: int
    converged: bool


def _inverse_distance_matrix(positions: np.ndarray) -> np.ndarray:
    """Return exact pairwise inverse distances with a zero diagonal."""
    shifted = positions - np.mean(positions, axis=0)
    squared_norm = np.sum(shifted * shifted, axis=1)
    distance = shifted @ shifted.T
    distance *= -2.0
    distance += squared_norm[:, None]
    distance += squared_norm[None, :]
    np.maximum(distance, 0.0, out=distance)
    np.sqrt(distance, out=distance)
    np.fill_diagonal(distance, np.inf)
    if np.any(distance == 0.0):
        raise ValueError(
            "Stellar self-binding is undefined for distinct particles at "
            "identical positions."
        )
    np.reciprocal(distance, out=distance)
    return distance


def _blocked_specific_potential(
    positions: np.ndarray,
    masses: np.ndarray,
    candidate: np.ndarray,
    max_matrix_bytes: int,
) -> np.ndarray:
    """Calculate exact potentials in target blocks against all candidates."""
    source_index = np.flatnonzero(candidate)
    if len(source_index) == 0:
        return np.zeros(len(positions))

    shifted = positions - np.mean(positions, axis=0)
    source_position = shifted[source_index]
    source_mass = masses[source_index]
    source_squared_norm = np.sum(source_position * source_position, axis=1)
    source_lookup = np.full(len(positions), -1, dtype=np.int64)
    source_lookup[source_index] = np.arange(len(source_index))
    bytes_per_row = np.dtype(float).itemsize * len(source_index)
    block_size = max(1, min(len(positions), max_matrix_bytes // bytes_per_row))
    potential = np.empty(len(positions))

    for start in range(0, len(positions), block_size):
        stop = min(start + block_size, len(positions))
        target_position = shifted[start:stop]
        target_squared_norm = np.sum(target_position * target_position, axis=1)
        inverse_distance = target_position @ source_position.T
        inverse_distance *= -2.0
        inverse_distance += target_squared_norm[:, None]
        inverse_distance += source_squared_norm[None, :]
        np.maximum(inverse_distance, 0.0, out=inverse_distance)
        np.sqrt(inverse_distance, out=inverse_distance)

        target_index = np.arange(start, stop)
        self_column = source_lookup[target_index]
        self_row = np.flatnonzero(self_column >= 0)
        inverse_distance[self_row, self_column[self_row]] = np.inf
        if np.any(inverse_distance == 0.0):
            raise ValueError(
                "Stellar self-binding is undefined for distinct particles at "
                "identical positions."
            )
        np.reciprocal(inverse_distance, out=inverse_distance)
        potential[start:stop] = (
            -GRAVITATIONAL_CONSTANT * (inverse_distance @ source_mass)
        )
    return potential


def calculate_bound_fraction(
    particles: Particles,
    max_iterations: int = DEFAULT_MAX_ITERATIONS,
    max_matrix_bytes: int = DEFAULT_MAX_MATRIX_BYTES,
) -> BoundFractionResult:
    """Calculate instantaneous binding to the stellar self-potential.

    The calculation begins with every valid star as a candidate. Each
    iteration calculates the candidate centre-of-mass frame and classifies all
    valid stars by negative specific energy in the potential generated by the
    current candidates. Stars may enter or leave between iterations. The
    calculation stops at unchanged membership, a repeated membership state, or
    ``max_iterations``.

    The exact inverse-distance matrix is cached when it fits within
    ``max_matrix_bytes``. Larger calculations use exact target blocks against
    every candidate source; interactions between blocks are not omitted.

    Warning:
        This function excludes gas and every other external potential. Its
        result is a stellar self-bound fraction, not necessarily the bound
        fraction of the combined star--gas system. Interpretation depends on
        the remaining gas fraction and its spatial distribution.

    Args:
        particles: Stellar AMUSE particles with mass, position, and velocity.
        max_iterations: Positive maximum number of membership updates.
        max_matrix_bytes: Positive working-memory budget for pairwise distance
            arrays. This changes the computational path, not the exact result.

    Returns:
        Labels, centres, masses, fractions, and convergence information for
        this snapshot.

    Raises:
        ValueError: If configuration values are invalid, no valid stars remain,
            total valid mass is invalid, particle keys are unsuitable, or two
            distinct valid particles occupy exactly the same position.
    """
    if isinstance(max_iterations, bool) or not isinstance(max_iterations, int):
        raise ValueError("max_iterations must be a positive integer.")
    if max_iterations < 1:
        raise ValueError("max_iterations must be a positive integer.")
    if isinstance(max_matrix_bytes, bool) or not isinstance(max_matrix_bytes, int):
        raise ValueError("max_matrix_bytes must be a positive integer.")
    if max_matrix_bytes < np.dtype(float).itemsize:
        raise ValueError("max_matrix_bytes must be at least 8 bytes.")

    positions = np.column_stack(
        (
            particles.x.value_in(units.pc),
            particles.y.value_in(units.pc),
            particles.z.value_in(units.pc),
        )
    )
    velocities = np.column_stack(
        (
            particles.vx.value_in(units.kms),
            particles.vy.value_in(units.kms),
            particles.vz.value_in(units.kms),
        )
    )
    masses = np.asarray(particles.mass.value_in(units.MSun), dtype=float)
    particle_key = np.asarray(particles.key)
    if particle_key.ndim != 1 or particle_key.dtype.kind not in "iu":
        raise ValueError("Stellar self-binding requires one integer key per particle.")
    if len(particle_key) != len(particles) or np.any(particle_key < 0):
        raise ValueError("Stellar self-binding requires non-negative particle keys.")
    if len(np.unique(particle_key)) != len(particle_key):
        raise ValueError("Stellar self-binding requires unique particle keys.")
    particle_key = particle_key.astype(np.uint64, copy=False)

    valid = (
        np.all(np.isfinite(positions), axis=1)
        & np.all(np.isfinite(velocities), axis=1)
        & np.isfinite(masses)
        & (masses > 0.0)
    )
    if not np.any(valid):
        raise ValueError(
            "Stellar self-binding requires finite positions and velocities "
            "and positive finite stellar masses."
        )

    valid_positions = np.ascontiguousarray(positions[valid], dtype=float)
    valid_velocities = np.ascontiguousarray(velocities[valid], dtype=float)
    valid_masses = np.ascontiguousarray(masses[valid], dtype=float)
    total_mass = float(np.sum(valid_masses))
    if not np.isfinite(total_mass) or total_mass <= 0.0:
        raise ValueError("Stellar self-binding requires a positive finite total mass.")

    matrix_bytes = len(valid_masses) ** 2 * np.dtype(float).itemsize
    inverse_distance = (
        _inverse_distance_matrix(valid_positions)
        if matrix_bytes <= max_matrix_bytes
        else None
    )
    candidate = np.ones(len(valid_masses), dtype=bool)
    seen = {np.packbits(candidate).tobytes()}
    converged = False
    centre_position = np.full(3, np.nan)
    centre_velocity = np.full(3, np.nan)

    for n_iterations in range(1, max_iterations + 1):
        if np.any(candidate):
            candidate_mass = valid_masses[candidate]
            candidate_total_mass = float(np.sum(candidate_mass))
            centre_position = np.sum(
                valid_positions[candidate] * candidate_mass[:, None], axis=0
            ) / candidate_total_mass
            centre_velocity = np.sum(
                valid_velocities[candidate] * candidate_mass[:, None], axis=0
            ) / candidate_total_mass
            if inverse_distance is not None:
                source_mass = valid_masses * candidate
                specific_potential = (
                    -GRAVITATIONAL_CONSTANT * (inverse_distance @ source_mass)
                )
            else:
                specific_potential = _blocked_specific_potential(
                    valid_positions,
                    valid_masses,
                    candidate,
                    max_matrix_bytes,
                )
            relative_velocity = valid_velocities - centre_velocity
            specific_kinetic = 0.5 * np.sum(
                relative_velocity * relative_velocity, axis=1
            )
            updated = specific_kinetic + specific_potential < 0.0
        else:
            centre_position = np.full(3, np.nan)
            centre_velocity = np.full(3, np.nan)
            updated = candidate.copy()

        if np.array_equal(updated, candidate):
            converged = True
            candidate = updated
            break
        signature = np.packbits(updated).tobytes()
        candidate = updated
        if signature in seen:
            break
        seen.add(signature)

    # The final returned centre always describes the returned candidate set,
    # including a state reached on the final allowed or repeated iteration.
    if np.any(candidate):
        candidate_mass = valid_masses[candidate]
        candidate_total_mass = float(np.sum(candidate_mass))
        centre_position = np.sum(
            valid_positions[candidate] * candidate_mass[:, None], axis=0
        ) / candidate_total_mass
        centre_velocity = np.sum(
            valid_velocities[candidate] * candidate_mass[:, None], axis=0
        ) / candidate_total_mass
    else:
        candidate_total_mass = 0.0
        centre_position = np.full(3, np.nan)
        centre_velocity = np.full(3, np.nan)

    labels = np.full(len(particles), -1, dtype=np.int8)
    labels[valid] = candidate.astype(np.int8)
    n_valid = int(np.count_nonzero(valid))
    n_bound = int(np.count_nonzero(candidate))
    return BoundFractionResult(
        particle_key=particle_key,
        bound=labels,
        centre_position=centre_position | units.pc,
        centre_velocity=centre_velocity | units.kms,
        n_present=len(particles),
        n_valid=n_valid,
        n_bound=n_bound,
        stellar_mass=total_mass | units.MSun,
        bound_mass=candidate_total_mass | units.MSun,
        bound_number_fraction=n_bound / n_valid,
        bound_mass_fraction=candidate_total_mass / total_mass,
        n_iterations=n_iterations,
        converged=converged,
    )


BOUND_FRACTION_OUTPUTS = {
    "centre_x": "pc",
    "centre_y": "pc",
    "centre_z": "pc",
    "centre_vx": "km/s",
    "centre_vy": "km/s",
    "centre_vz": "km/s",
    "n_present": "1",
    "n_valid": "1",
    "n_bound": "1",
    "stellar_mass": "Msun",
    "bound_mass": "Msun",
    "bound_number_fraction": "1",
    "bound_mass_fraction": "1",
    "n_iterations": "1",
    "converged": "1",
}
"""Canonical scalar fields for the bound-fraction diagnostic."""


def measure_bound_fraction(particles: Particles) -> SnapshotDiagnosticResult:
    """Adapt the standalone calculation to the diagnostic storage contract."""
    result = calculate_bound_fraction(particles)
    series = {
        "stellar_self_potential": {
            "centre_x": result.centre_position[0],
            "centre_y": result.centre_position[1],
            "centre_z": result.centre_position[2],
            "centre_vx": result.centre_velocity[0],
            "centre_vy": result.centre_velocity[1],
            "centre_vz": result.centre_velocity[2],
            "n_present": result.n_present | units.none,
            "n_valid": result.n_valid | units.none,
            "n_bound": result.n_bound | units.none,
            "stellar_mass": result.stellar_mass,
            "bound_mass": result.bound_mass,
            "bound_number_fraction": (
                result.bound_number_fraction | units.none
            ),
            "bound_mass_fraction": result.bound_mass_fraction | units.none,
            "n_iterations": result.n_iterations | units.none,
            "converged": int(result.converged) | units.none,
        }
    }
    return SnapshotDiagnosticResult(
        series=series,
        particles={
            "stellar_self_potential": ParticleSnapshotResult(
                particle_key=result.particle_key,
                values={"bound": result.bound},
            )
        },
    )


